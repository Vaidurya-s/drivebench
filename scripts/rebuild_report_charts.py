#!/usr/bin/env python3
r"""Write the results tables used by the DriveBench report.

Reads ``report/metrics_summary.json`` (from ``scripts/rebuild_report_metrics.py``) and
writes ``report/results_table.tex`` (``\input`` by the report) and ``report/results_tables.md``.
The best value in a group is shaded unless every controller ties.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "report"
IDS = ("pid", "optimized_pid", "lqr", "mpc")
HEAD = ("PID", "Opt.", "LQR", "MPC")


def _f(v, nd):
    return "n/a" if v is None else f"{v:.{nd}f}"


def _cells(vals, nd):
    ok = [round(v, nd) for v in vals if v is not None]
    best = min(ok) if ok else None
    tie_all = len(ok) == len(vals) and len(set(ok)) == 1
    out = []
    for v in vals:
        c = _f(v, nd)
        if v is not None and not tie_all and round(v, nd) == best:
            c = r"\cellcolor{best}\textbf{" + c + "}"
        out.append(c)
    return out


def _fmt_metric(key: str, v) -> str:
    if v is None:
        return "n/a"
    if key == "iae":
        return f"{v:.0f}" if v >= 100 else f"{v:.1f}"
    if key == "exec_ms_mean":
        return f"{v:.3f}" if v < 0.1 else f"{v:.1f}"
    if key in ("settling_time_s", "rise_time_s", "current_limit_s", "voltage_saturation_s", "max_current_a",
               "overshoot_pct", "rms_current_a"):
        return f"{v:.2f}"
    return f"{v:.3g}"


def write_numbers(data: dict) -> None:
    r"""``report/numbers.tex``: every figure the prose quotes, as ``\M{scenario}{controller}{metric}``."""
    lines = [
        r"% Generated by scripts/rebuild_report_charts.py from metrics_summary.json. Do not edit.",
        r"\newcommand{\M}[3]{\csname M@#1@#2@#3\endcsname}",
    ]
    for sk, sc in data["scenarios"].items():
        for cid in IDS:
            for mk, mv in sc[cid].items():
                if isinstance(mv, (int, float)) or mv is None:
                    lines.append(
                        rf"\expandafter\def\csname M@{sk}@{cid}@{mk}\endcsname{{{_fmt_metric(mk, mv)}}}"
                    )
    rob = data.get("robustness_model_mismatch", {})
    for rk, rv in rob.items():
        if isinstance(rv, dict) and "iae" in rv:
            lines.append(rf"\expandafter\def\csname R@{rk}\endcsname{{{rv['iae']:.0f}}}")
    lq = data.get("lqr", {})
    for name, v in zip(("KI", "KW", "KX"), lq.get("gain_K", [])):
        lines.append(rf"\expandafter\def\csname L@{name}\endcsname{{{v:.3f}}}")
    for k in ("q_current", "q_speed", "q_integral", "r_voltage"):
        if k in lq:
            lines.append(rf"\expandafter\def\csname L@{k}\endcsname{{{lq[k]:g}}}")
    if "closed_loop_eigenvalues_abs" in lq:
        lines.append(rf"\expandafter\def\csname L@maxpole\endcsname{{{max(lq['closed_loop_eigenvalues_abs']):.3f}}}")
    wins = {c: 0 for c in IDS}
    ties = 0
    for sc in data["scenarios"].values():
        iae = {c: sc[c]["iae"] for c in IDS}
        best = min(iae.values())
        near = [c for c in IDS if iae[c] <= best * 1.005]
        if len(near) == 1:
            wins[near[0]] += 1
        else:
            ties += 1
    import math

    logs = {c: [] for c in IDS}
    for sc in data["scenarios"].values():
        best = min(sc[c]["iae"] for c in IDS)
        for c in IDS:
            logs[c].append(math.log(sc[c]["iae"] / best))
    for c in IDS:
        gm = math.exp(sum(logs[c]) / len(logs[c]))
        lines.append(rf"\expandafter\def\csname L@gm{c}\endcsname{{{gm:.2f}}}")
    lines.append(rf"\expandafter\def\csname L@winsMPC\endcsname{{{wins['mpc']}}}")
    lines.append(rf"\expandafter\def\csname L@winsLQR\endcsname{{{wins['lqr']}}}")
    lines.append(rf"\expandafter\def\csname L@winsPID\endcsname{{{wins['pid'] + wins['optimized_pid']}}}")
    lines.append(rf"\expandafter\def\csname L@winsTie\endcsname{{{ties}}}")
    g = data.get("optimized_pid_gains", {})
    for k, v in g.items():
        lines.append(rf"\expandafter\def\csname G@{k}\endcsname{{{v:.4g}}}")
    (REPORT / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    data = json.loads((REPORT / "metrics_summary.json").read_text(encoding="utf-8"))
    write_numbers(data)
    rows_tex, rows_md = [], []
    for sc in data["scenarios"].values():
        iae = [sc[c]["iae"] for c in IDS]
        st = [sc[c]["settling_time_s"] for c in IDS]
        il = [sc[c]["current_limit_s"] for c in IDS]
        cells = _cells(iae, 0) + _cells(st, 2) + _cells(il, 2)
        rows_tex.append(sc["title"].replace("&", r"\&") + " & " + " & ".join(cells) + r" \\")
        rows_md.append(
            f"| {sc['title']} | "
            + " | ".join([_f(v, 0) for v in iae] + [_f(v, 2) for v in st] + [_f(v, 2) for v in il])
            + " |"
        )
    head1 = (
        r"\textbf{Scenario} & \multicolumn{4}{c}{IAE [RPM\,s]} & \multicolumn{4}{c}{Settling [s]}"
        r" & \multicolumn{4}{c}{Current-limited [s]} \\"
    )
    head2 = " & " + " & ".join(HEAD * 3) + r" \\"
    tex = "\n".join(
        [
            r"\begin{tabular}{@{}l" + "r" * 12 + r"@{}}",
            r"\toprule",
            head1,
            r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}\cmidrule(lr){10-13}",
            head2,
            r"\midrule",
            *rows_tex,
            r"\bottomrule",
            r"\end{tabular}",
            "",
        ]
    )
    (REPORT / "results_table.tex").write_text(tex, encoding="utf-8")
    md = [
        "| Scenario | " + " | ".join(f"IAE {h}" for h in HEAD) + " | "
        + " | ".join(f"Settling {h}" for h in HEAD) + " | "
        + " | ".join(f"I-limit {h}" for h in HEAD) + " |",
        "| --- |" + " ---: |" * 12,
        *rows_md,
    ]
    (REPORT / "results_tables.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote report/results_table.tex and results_tables.md")


if __name__ == "__main__":
    main()
